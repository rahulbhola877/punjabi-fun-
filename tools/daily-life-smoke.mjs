import { launch, waitFor, sleep, snap, tap, walkTo, clearDialogues } from './pt-lib.mjs';
import fs from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:4173/';
const label = process.env.LABEL ?? 'local';
const { browser, page, log } = await launch(`${base}?probe`, { w:1280, h:720, settings:{ quality:'high', renderer:'webgl' }, storage:{ 'gediroute.hour':'23' } });
const report = {};
fs.mkdirSync('artifacts/daily-life', { recursive:true });
const check = (ok, msg) => { if (!ok) throw Error(msg); };
const visit = () => page.evaluate(() => window.__pfs.visit());
async function waitVisit(stage, timeout=45000) {
  const end=Date.now()+timeout;
  while(Date.now()<end) { const v=await visit(); if(v?.stage===stage) return v; await sleep(250); }
  throw Error(`Expected visit ${stage}; got ${JSON.stringify(await visit())}`);
}
try {
  await page.waitForFunction(()=>window.__pfs?.snapshot().state==='title',null,{timeout:180000});
  await page.locator('#title .menu button').first().click();
  await page.locator('#title .looks button').first().click();
  await waitFor(page,s=>s.state==='playing');
  report.startHour=await page.evaluate(()=>window.__pfs.hour());
  console.log('Started', report.startHour);
  check(report.startHour.startsWith('09'), `Stale night start: ${report.startHour}`);
  const h=await page.evaluate(()=>{
    const hs=window.__pfs.openHouses();
    return window.__pfs.bells().find(b=>b.id==='santH159') ?? window.__pfs.bells().find(b=>hs.find(h=>h.id===b.id)?.d>40 && b.id.startsWith('sant'));
  });
  check(h,'No visitable home'); report.house=h;
  await page.evaluate(h=>{window.__pfs.teleport(h.bell.x,h.bell.z,h.rot+Math.PI);window.__pfs.hour(23);},h);
  await sleep(2500); report.nightCrowd=await page.evaluate(()=>window.__pfs.crowd());
  await tap(page,'KeyE'); await waitVisit('night');
  report.night=await snap(page);
  console.log('Night response passed');
  check(!report.night.dialogueOpen,'Night bell incorrectly invites player');
  check(report.night.bubbles.some(t=>/[\u0a00-\u0a7f]/.test(t)),'Night bell missing Punjabi reaction');
  await page.screenshot({path:`artifacts/daily-life/${label}-night.png`});
  await sleep(9000);
  await page.evaluate(()=>window.__pfs.hour(9));
  await sleep(1000); await tap(page,'KeyE');
  await waitFor(page,s=>s.dialogueOpen,45000);
  report.invitation=await page.locator('.dialogue').innerText();
  console.log('Invitation received');
  await page.keyboard.press('1'); await sleep(500);
  const local=(u,z)=>({x:h.ox+u*Math.cos(h.rot)+z*Math.sin(h.rot),z:h.oz-u*Math.sin(h.rot)+z*Math.cos(h.rot)});
  // Walk through the actual gate opening, along the yard, then through the doorway.
  await walkTo(page,[local(h.gateU,1),local(h.gateU,-1.6),local(h.doorU+h.doorW/2,-h.yd+1.4)],{tol:.14,timeout:45000});
  await walkTo(page,[local(h.doorU+h.doorW/2,-h.yd-1.4)],{tol:.25,timeout:30000});
  await waitVisit('inside');
  console.log('Entered home');
  const home=await page.evaluate(id=>window.__pfs.openHouses().find(h=>h.id===id),h.id);
  await walkTo(page,[home.talk],{tol:1.2,timeout:20000});
  await sleep(500); report.indoors=await snap(page);
  check(report.indoors.interactionId?.startsWith('visit_'),'No indoor conversation prompt');
  await tap(page,'KeyE'); await waitFor(page,s=>s.dialogueOpen,10000);
  report.conversation=await page.locator('.dialogue').innerText();
  await page.screenshot({path:`artifacts/daily-life/${label}-visit.png`});
  await clearDialogues(page);
  await page.evaluate(()=>window.__pfs.teleport(-1005,-600,0)); await sleep(3500);
  report.neighbourhood=await snap(page);
  await page.screenshot({path:`artifacts/daily-life/${label}-neighbourhood.png`});
  await page.evaluate(()=>window.__pfs.teleport(-855,-1108,Math.PI)); await sleep(3500);
  const shops=await page.evaluate(()=>window.__pfs.cityShops().filter(s=>s.id.startsWith('bypass')));
  check(shops.length===6,'New shops have no functioning trade menus');
  const sh=shops[0];
  await page.evaluate(s=>window.__pfs.teleport(s.cx,s.cz,s.yaw+Math.PI),sh); await sleep(1800);
  report.shopPrompt=(await snap(page)).prompt;
  await tap(page,'KeyE'); await sleep(500);
  check((await snap(page)).modalOpen || (await snap(page)).dialogueOpen,'New shop does not open');
  await page.screenshot({path:`artifacts/daily-life/${label}-market.png`});
  await page.keyboard.press('Escape'); await clearDialogues(page);
  await page.evaluate(()=>window.__pfs.teleport(-205,-160,0)); await sleep(1500);
  const duty=await page.evaluate(()=>window.__pfs.snapshot().vehicles.find(v=>v.paint==='police' && v.id.startsWith('post_')) ?? window.__pfs.snapshot().vehicles.find(v=>v.paint==='police'));
  check(duty,'No duty vehicle at checkpoint');
  await page.evaluate(v=>window.__pfs.teleport(v.x+1.7,v.z,0),duty); await sleep(800);
  check((await snap(page)).interactionId!==`veh_${duty.id}`,'Police vehicle is available to ordinary player');
  report.policeVehicleReserved=duty.id;
  await page.evaluate(()=>window.__pfs.teleport(-545,-1137,Math.PI)); await sleep(1800);
  report.dhabaPrompt=(await snap(page)).prompt;
  check(report.dhabaPrompt?.includes('Truckers Dhaba'),'Bypass dhaba has no food interaction');
  await tap(page,'KeyE'); await sleep(400);
  check((await snap(page)).modalOpen || (await snap(page)).dialogueOpen,'Dhaba menu does not open');
  await page.keyboard.press('Escape'); await clearDialogues(page);
  await page.evaluate(()=>{window.__pfs.driveAt('car',-627.5,-1126,0);window.__pfs.fuel(.4);}); await sleep(1800);
  report.fuelBefore=await page.evaluate(()=>window.__pfs.fuel());
  check((await snap(page)).prompt?.includes('Fill the tank'),'Bypass pump has no refuel action');
  await tap(page,'KeyE'); await sleep(400);
  report.fuelAfter=await page.evaluate(()=>window.__pfs.fuel());
  check(report.fuelAfter>.99 && report.fuelBefore<.5,'Bypass pump failed to refill tank');
  await page.evaluate(()=>window.__pfs.placeVehicle(-227,-165.5,Math.PI/2));
  await waitFor(page,s=>s.dialogueOpen,15000);
  report.compliance=await snap(page);
  check(report.compliance.wanted===0,'Stopping at checkpoint incorrectly starts pursuit');
  await clearDialogues(page);
  await page.evaluate(()=>window.__pfs.placeVehicle(-252,-165.5,Math.PI/2)); await sleep(1000);
  await page.keyboard.down('KeyW'); await sleep(13000); await page.keyboard.up('KeyW');
  report.police=await snap(page);
  check(report.police.wanted>=1 && report.police.chasing,'Ignoring police stop order did not start pursuit');
  report.errors=report.police.errors; report.log=log;
  check(!report.errors.length && !log.some(s=>/^\[(error|pageerror)\]/.test(s)),'Runtime errors');
  console.log(JSON.stringify({startHour:report.startHour,house:h.id,police:{wanted:report.police.wanted,chasing:report.police.chasing},shopPrompt:report.shopPrompt,errors:report.errors}));
} catch(e) { report.failure=String(e); report.last=await snap(page); console.error(e); await page.screenshot({path:`artifacts/daily-life/${label}-failure.png`}); process.exitCode=1; }
finally { fs.writeFileSync(`artifacts/daily-life/${label}.json`,JSON.stringify(report,null,2)); await browser.close(); }
